import { z } from 'zod';
import { publicPath } from '../utils/public-path';

export const restaurantSchema = z.object({
  id: z.string(),
  name: z.string(),
  city: z.string(),
  address: z.string(),
  kind: z.enum(['pizza', 'bakery', 'hotel', 'other']),
  image: z.string(),
  imageAlt: z.object({ it: z.string().nullable(), en: z.string().nullable() }).optional(),
  website: z.string().url().optional(),
  lat: z.number().min(-90).max(90),
  lng: z.number().min(-180).max(180),
  oven: z.string(),
  mapsUrl: z.string().url(),
  locationStatus: z.string(),
  locationNote: z.string(),
  coordinatePrecision: z.enum(['address', 'place', 'place-fallback']),
  isPublished: z.boolean().optional(),
  description: z.object({ it: z.string(), en: z.string() }),
});

export type Restaurant = z.infer<typeof restaurantSchema>;

export function shopImage(image: string, variant: 'cards' | 'heroes') {
  if (!image.startsWith('/shops/')) return image.startsWith('/') ? publicPath(image) : image;
  const filename = image
    .split('/')
    .pop()
    ?.replace(/\.[^.]+$/, '');
  return filename ? publicPath(`/shops-webp/${variant}/${filename}.webp`) : image;
}

